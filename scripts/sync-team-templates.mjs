import ts from "typescript";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const sources = {
  composition: "image-prompt-composition/composition.ts",
  migration: "image-prompt-migration/migration.ts",
  text: "user-optimize/user-prompt-basic.ts",
};
const systems = {};
for (const [key, path] of Object.entries(sources)) {
  const name = new URL(
    `packages/core/src/services/template/default-templates/${path}`,
    root,
  );
  const source = ts.createSourceFile(
    fileURLToPath(name),
    await readFile(name, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  const visit = (node) => {
    if (ts.isObjectLiteralExpression(node)) {
      const properties = new Map(
        node.properties
          .filter(ts.isPropertyAssignment)
          .map((p) => [
            p.name.getText(source).replace(/['"]/g, ""),
            p.initializer,
          ]),
      );
      if (properties.get("role")?.getText(source) === "'system'") {
        const content = properties.get("content");
        if (
          content &&
          (ts.isNoSubstitutionTemplateLiteral(content) ||
            ts.isStringLiteral(content))
        )
          systems[key] = content.text;
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  if (!systems[key]) throw new Error(`Missing system prompt: ${path}`);
}
const output = `// Generated by scripts/sync-team-templates.mjs from the original core templates.\n// Keep this runtime-neutral so Edge Functions do not load the browser/Node core bundle.\nexport const TEMPLATE_SYSTEMS = ${JSON.stringify(systems, null, 2)} as const\n`;
const target = new URL(
  "supabase/functions/_shared/studio-template-context.ts",
  root,
);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error(
      "Run node scripts/sync-team-templates.mjs to update shared prompts",
    );
} else await writeFile(target, output);
